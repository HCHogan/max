-- Model usage, and the historian's summaries.

create table llm_usage (
    id bigint generated by default as identity primary key,
    conversation_id bigint references conversations,
    turn_id bigint references turns,
    purpose text not null check (purpose in ('turn', 'intent', 'historian', 'caption')),
    provider text not null,
    model text not null,
    effort text,
    input bigint not null,
    -- Of the input, how much hit the provider's prefix cache.
    cached bigint not null,
    output bigint not null,
    -- Of the output, how much was reasoning.
    reasoning bigint not null,
    -- Millionths of a US dollar, when the price is known.
    cost_micros bigint,
    at timestamptz not null
);

create index on llm_usage (at);

-- For the exclusion constraint below: = on bigint in a GiST index.
create extension if not exists btree_gist;

-- Written once by the historian, at three levels; see "衰减".
create table summaries (
    id bigint generated by default as identity primary key,
    conversation_id bigint not null references conversations,
    first_message_id bigint not null references messages,
    last_message_id bigint not null references messages,
    started_at timestamptz not null,
    ended_at timestamptz not null,
    title text not null,
    kind text not null,
    importance smallint not null check (importance between 1 and 100),
    p1 text not null,
    p2 text,
    p3 text,
    model text not null,
    created_at timestamptz not null,
    status text not null default 'active' check (status in ('active', 'superseded')),
    superseded_by bigint references summaries,
    check (first_message_id <= last_message_id),
    check ((status = 'superseded') = (superseded_by is not null)),
    -- Active summaries of a conversation never overlap.
    exclude using gist (
        conversation_id with =,
        int8range(first_message_id, last_message_id, '[]') with &&
    ) where (status = 'active')
);
