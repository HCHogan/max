-- Each model call of the historian: the stretch it read and what came of
-- it, the answer when there was one, the error when nothing was
-- published. The summaries it published are written in the same
-- transaction. See "historian" in docs/rust-rewrite.md.

create table summary_runs (
    id bigint generated by default as identity primary key,
    conversation_id bigint not null references conversations,
    first_message_id bigint not null references messages,
    last_message_id bigint not null references messages,
    -- quiet: the conversation went quiet; pressure: its tail grew past the
    -- high watermark; compact: !compact.
    reason text not null check (reason in ('quiet', 'pressure', 'compact')),
    model text not null,
    output text,
    error text,
    started_at timestamptz not null,
    finished_at timestamptz not null,
    check (output is not null or error is not null)
);

create index on summary_runs (conversation_id, id);
