-- Conversations, the people in them, and their platform accounts.
-- See "schema" and "身份" in docs/rust-rewrite.md.

create table conversations (
    id bigint generated by default as identity primary key,
    kind text not null check (kind in ('group', 'direct')),
    title text,
    created_at timestamptz not null default now()
);

-- A person. Accounts point here; merging two people points the merged row
-- at the one kept, and readers follow merged_into once.
create table principals (
    id bigint generated by default as identity primary key,
    display_name text not null,
    merged_into bigint references principals check (merged_into <> id),
    created_at timestamptz not null default now()
);

-- A platform account, Max's own included.
create table identities (
    id bigint generated by default as identity primary key,
    principal_id bigint not null references principals,
    platform text not null check (platform in ('qq', 'qq_legacy', 'matrix')),
    native_user_id text not null,
    created_at timestamptz not null default now(),
    unique (platform, native_user_id)
);

-- Where a conversation lives on a platform, and which of Max's accounts
-- serves it there. native_id is the adapter's: `group:<n>` or `private:<n>`
-- on QQ, the room id on Matrix.
create table endpoints (
    id bigint generated by default as identity primary key,
    conversation_id bigint not null references conversations,
    platform text not null check (platform in ('qq', 'qq_legacy', 'matrix')),
    native_id text not null,
    self_identity_id bigint not null references identities,
    created_at timestamptz not null default now(),
    unique (platform, self_identity_id, native_id)
);

create index on endpoints (conversation_id);

-- What !model, !effort, !persona, !proactive and !clear --all set.
create table conversation_settings (
    conversation_id bigint primary key references conversations,
    model text,
    effort text,
    persona text,
    proactive boolean not null default true,
    -- Messages up to here stay out of prompts. References messages, from 0002.
    cleared_upto bigint,
    updated_at timestamptz not null
);
