-- What Max in one conversation asked Max in another that has no answer
-- yet: a row from when Max there is shown the question until it answers,
-- or `/stop` there or `/unlink` removes it. Its id is the question's
-- number, `ask#5`. One older than `ASK_DAYS` is neither shown nor
-- answered. See "Asking another conversation" in docs/design/jobs.md.
create table questions (
    id bigint generated by default as identity primary key,
    asker_id bigint not null references conversations,
    asked_id bigint not null references conversations,
    question text not null,
    asked_at timestamptz not null,
    check (asker_id <> asked_id)
);

create index on questions (asked_id);
create index on questions (asker_id);
