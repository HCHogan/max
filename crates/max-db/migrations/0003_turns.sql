-- What Max did behind the scenes: four kinds of record per turn, append
-- only. A turn's state is which of them it has. See "turn 记录".

create table turns (
    id bigint generated by default as identity primary key,
    conversation_id bigint not null references conversations,
    -- t#N for the model, counted per conversation.
    ordinal integer not null,
    -- The first inputs, as max_core::run::Input values.
    trigger jsonb not null,
    -- The snapshot position: the base context covers messages up to here.
    from_id bigint not null references messages,
    started_at timestamptz not null,
    unique (conversation_id, ordinal)
);

alter table messages add foreign key (turn_id) references turns;

-- Attempt 1 is the start; each resume after a restart is the next.
create table turn_resumes (
    turn_id bigint not null references turns,
    attempt integer not null check (attempt >= 2),
    resumed_at timestamptz not null,
    primary key (turn_id, attempt)
);

-- The core at the end of an attempt: its RunRecord, which replays.
create table turn_snapshots (
    turn_id bigint not null references turns,
    attempt integer not null check (attempt >= 1),
    run jsonb not null,
    -- The timeline's head when it was taken; a resume feeds what came after.
    upto_id bigint not null references messages,
    taken_at timestamptz not null,
    primary key (turn_id, attempt)
);

create table turn_outcomes (
    turn_id bigint primary key references turns,
    outcome text not null check (
        outcome in ('answered', 'silent', 'interrupted', 'failed', 'expired', 'lost')
    ),
    failure text check (failure in ('model', 'context_exhausted', 'input_too_large')),
    error text,
    finished_at timestamptz not null,
    check ((outcome = 'failed') = (failure is not null)),
    check (case when failure = 'model' then error is not null else error is null end)
);
