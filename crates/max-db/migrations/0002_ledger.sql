-- The ledger: every row of every conversation's timeline, append only, and
-- what became of what Max sent. See "ledger", "时间线" and "出站".

create table messages (
    -- In one conversation, id order is the order the conversation actor
    -- committed rows: the timeline.
    id bigint generated by default as identity primary key,
    conversation_id bigint not null references conversations,
    endpoint_id bigint not null references endpoints,
    -- A snapshot of the sender as they were, so a rename doesn't rewrite
    -- old lines.
    sender_identity_id bigint not null references identities,
    sender_name text not null,
    sender_role text check (sender_role in ('owner', 'admin', 'member')),
    -- The platform's id for an inbound row. What Max sent has its platform
    -- id in deliveries.
    native_id text,
    sent_at timestamptz not null,
    received_at timestamptz not null,
    kind text not null check (kind in ('chat', 'command', 'event')),
    event text check (event in ('edit', 'unsend')),
    reply_to_id bigint references messages,
    -- The row an edit or unsend is about.
    target_id bigint references messages,
    -- max_core::message::Node values: the content, or the new content of an
    -- edit.
    nodes jsonb not null,
    raw jsonb not null,
    -- Rendered text, for search.
    text text not null,
    -- For what Max said: the turn, from 0003, and the segment's place in
    -- its output.
    turn_id bigint,
    segment integer,
    unique (endpoint_id, native_id),
    check ((kind = 'event') = (event is not null)),
    check ((event is not null) = (target_id is not null)),
    check (kind <> 'event' or reply_to_id is null)
);

create index on messages (conversation_id, id);
-- The roster: each sender's latest name and role in an endpoint.
create index on messages (endpoint_id, sender_identity_id, id);
create index on messages (target_id) where target_id is not null;
create index on messages (turn_id) where turn_id is not null;

alter table conversation_settings
    add foreign key (cleared_upto) references messages;

-- One row per message and endpoint Max sent it to, written by the
-- platform's sender once it knows.
create table deliveries (
    id bigint generated by default as identity primary key,
    message_id bigint not null references messages,
    endpoint_id bigint not null references endpoints,
    status text not null check (status in ('sent', 'failed', 'unknown')),
    native_id text,
    error text,
    at timestamptz not null,
    unique (message_id, endpoint_id),
    unique (endpoint_id, native_id),
    check ((status = 'sent') = (native_id is not null)),
    check ((status = 'failed') = (error is not null))
);
