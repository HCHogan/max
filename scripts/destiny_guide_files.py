"""File layout shared by the Destiny guide generators.

data/destiny-guides is mounted read-only in every command sandbox at
/data/destiny, so the layout is written for rg/head/sed and Python:

  en/<source>/<sheet>.csv           current worksheets, original English
  zh/<source>/<sheet>.csv           Chinese copies with identical coordinates
  archive/{en,zh}/<source>/...      hidden, old and ignore worksheets
  meta/<source>/<sheet>.json        merged ranges, notes, links, formulas
  catalog.tsv, names.tsv            generated by the translation step
  .state/                           generator bookkeeping (hashes, glossary)

One worksheet row per physical line: in-cell backslashes, newlines and carriage
returns are written as \\\\, \\n and \\r, so line N is spreadsheet row N.
"""

import csv
import hashlib
import io
import json
import re
import sqlite3
from pathlib import Path

SOURCES_INDEX = Path(".state/sources.json")
TRANSLATION_INDEX = Path(".state/translation.json")
GLOSSARY = Path(".state/glossary.json")
# Reviewed line translations ({english line: chinese line}); they take
# precedence over cached and machine translations and survive regeneration.
OVERRIDES = Path(".state/translation-overrides.json")
# Bare frame labels ("High-Impact", "Vortex") name a weapon frame only in these
# workbooks; elsewhere the same word can be an ability or a fireteam role.
FRAME_SOURCES = {"court", "endgame-analysis"}
UNESCAPE = {"\\": "\\", "n": "\n", "r": "\r"}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def escape(text):
    return text.replace("\\", "\\\\").replace("\n", "\\n").replace("\r", "\\r")


def unescape(text):
    return re.sub(r"\\([\\nr])", lambda m: UNESCAPE[m[1]], text)


def grid_bytes(rows):
    """Serialize a rectangular grid; csv quotes commas and quotes, never newlines."""
    buffer = io.StringIO()
    csv.writer(buffer, lineterminator="\n").writerows([[escape(value) for value in row] for row in rows])
    return buffer.getvalue().encode("utf-8")


def read_grid(path):
    text = path.read_text(encoding="utf-8")
    # Split on \n only: str.splitlines would also break cells at U+2028 etc.
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return [[unescape(value) for value in row] for row in csv.reader(lines)]


def zh_path(path):
    """en/x/y.csv -> zh/x/y.csv; archive/en/x/y.csv -> archive/zh/x/y.csv."""
    parts = list(Path(path).parts)
    parts[parts.index("en")] = "zh"
    return Path(*parts).as_posix()


def frame_line(source, line, frames):
    """Official short frame name for a whole-line frame label, else None."""
    return frames.get(line.strip()) if source in FRAME_SOURCES else None


def open_memory(cache):
    cache.mkdir(parents=True, exist_ok=True)
    db = sqlite3.connect(cache / "memory.sqlite")
    db.execute("CREATE TABLE IF NOT EXISTS memory (original TEXT PRIMARY KEY, translated TEXT NOT NULL)")
    return db


def harvest_memory(data, db):
    """Remember the checked-in en->zh line pairs before English is replaced.

    Only sheets whose English still hashes to what was translated contribute.
    Frame lines are rewritten per workbook, so they are not reusable text.
    """
    index_file = data / TRANSLATION_INDEX
    if not index_file.exists():
        return 0
    index = json.loads(index_file.read_text())
    frames = set(index.get("frames", {}))
    pairs = []
    for sheet in index["sheets"]:
        en_file, zh_file = data / sheet["path"], data / sheet["zh_path"]
        if not (en_file.exists() and zh_file.exists()) or digest(en_file.read_bytes()) != sheet["original_sha256"]:
            continue
        pairs.append((sheet["title"], sheet["title_zh"]))
        for en_row, zh_row in zip(read_grid(en_file), read_grid(zh_file)):
            for en, zh in zip(en_row, zh_row):
                for a, b in zip(en.split("\n"), zh.split("\n")):
                    if a.strip() and not (sheet["source"] in FRAME_SOURCES and a.strip() in frames):
                        pairs.append((a, b))
    db.executemany("INSERT OR REPLACE INTO memory VALUES (?, ?)", pairs)
    db.commit()
    return len(pairs)
